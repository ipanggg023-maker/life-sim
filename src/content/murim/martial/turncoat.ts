const act = (r: Res, f: (l: Life, c: Ctx) => void): Res => Object.assign(((l: Life, c: Ctx) => { f(l, c); return r(l, c); }) as Res, { fx: r.fx });

const sect = (l: Life) => mySectFaction(l)?.name ?? "สำนัก";
const head = (l: Life) => !!l.power?.guild && l.flags.sectHead === l.power.guild;
const side = (l: Life) => mySectFaction(l)?.side;
const hiding = (l: Life) => !!l.flags.tnHiding && !!mySectFaction(l);
const dark = (l: Life) => hiding(l) && l.flags.tnMode === "dark";
const light = (l: Life) => hiding(l) && l.flags.tnMode === "light";
const sus = (n: number) => (l: Life) => { l.flags.tnSus = Math.max(0, Number(l.flags.tnSus ?? 0) + n); };
const endHiding = (l: Life) => { delete l.flags.tnHiding; delete l.flags.tnSus; };
const hide = (mode: "dark" | "light") => (l: Life) => { l.flags.tnHiding = true; l.flags.tnMode = mode; l.flags.tnSus = 0; };

/** ออกจากสำนัก · hunted = สำนักส่งคนตามล่า */
function leave(l: Life, hunted: boolean) {
  const f = mySectFaction(l);
  if (!f || !l.power) return;
  l.flags.tnFrom = f.id;
  if (hunted) { l.flags.tnHuntBy = f.name; shiftRep(l, f.id, -40); }
  if (l.flags.sectHead === f.id) delete l.flags.sectHead;
  l.power.guild = undefined;
  if (l.job?.careerId === "disciple") l.job = undefined;
  endHiding(l);
  log(l, `ชื่อคุณถูกขีดออกจากทะเบียนของ${f.name}`, "bad");
}
/** ชำระล้าง: เสียฝีมือหนึ่งขั้น แต่กลับมาเป็นคนของสำนักได้ */
function cleanse(l: Life) {
  if (l.power) l.power.rank = Math.max(0, l.power.rank - 1);
  shiftAlign(l, Math.max(0, -5 - alignment(l)));
  endHiding(l);
  l.flags.tnCleansed = true;
}

