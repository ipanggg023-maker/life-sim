const stepKey = (a: string) => `ssS_${a}`;
const ageKey = (a: string) => `ssA_${a}`;
const endKey = (a: string) => `ssE_${a}`;
export const activeArcs = (l: Life) => ARCS.filter((a) => l.flags[stepKey(a.id)] !== undefined && l.flags[endKey(a.id)] === undefined);
