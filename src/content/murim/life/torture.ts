const heat = (l: Life) => Number(l.flags.heat ?? 0);
const lowerHeat = (l: Life, n: number) => { l.flags.heat = Math.max(0, heat(l) - n); };
const SUSPECTS = ["คนแบกหามท่าเรือ", "ลูกจ้างโรงเตี๊ยม", "พ่อค้าเร่ต่างถิ่น", "คนตีเหล็กหน้าตลาด", "บัณฑิตสอบตก", "ทหารหนีทัพ"];
const run = (r: Res, f: (l: Life, c: Ctx) => void): Res => Object.assign((l: Life, c: Ctx) => { f(l, c); return r(l, c); }, { fx: r.fx });

/** ถูกจับในคดีหนัก → สอบสวนก่อนศาล (law.ts เรียก) */
export const needsInterrogation = (l: Life) => l.worldId === "murim" && heat(l) >= 40;

/** ชื่อเสียงของผู้สอบสวนที่ใช้การทรมานบ่อย */
function torturerRep(l: Life) {
  const n = (l.flags.tortured = Number(l.flags.tortured ?? 0) + 1);
  if (n === 3) log(l, "🗞️ ชาวเมืองเริ่มเรียกคุณลับหลังว่า \"มือปราบเหล็กเผา\" — แม่ค้าในตลาดเงียบเสียงทุกครั้งที่คุณเดินผ่าน", "bad");
}

