// ทางรอดเมื่อถูกจับได้: ใช้ร่วมกันทั้งราชสำนัก วังหลัง และสำนัก โอกาสขึ้นกับความสามารถจริงของตัวละคร
import type { Choice, Ctx } from "../../../engine/events";
import type { Life } from "../../../engine/types";
import { B, G, P, ab, type Res } from "../story/kit";

const with_ = (r: Res, f: (l: Life, c: Ctx) => void): Res => Object.assign(((l: Life, c: Ctx) => { f(l, c); return r(l, c); }) as Res, { fx: r.fx });

export interface Cover {
  /** รอด: ล้างข้อสงสัย */
  clear: (l: Life, c: Ctx) => void;
  /** ไม่รอด */
  caught: (l: Life, c: Ctx) => void;
  /** มีพรรคพวกช่วยได้ไหม */
  ally?: (l: Life) => boolean;
}

/** ห้าทางตามถนัด: สติปัญญา รูปลักษณ์ โชค ร่างกาย และพรรคพวก */
export function coverUp(o: Cover): Choice[] {
  const ok = (r: Res) => with_(r, o.clear);
  const no = (r: Res) => with_(r, o.caught);
  return [
    P("แก้ต่างทีละข้อจนคนฟังเงียบ", ab(0.35, "smarts", 0.7), ok(G("คุณชี้จุดขัดแย้งในคำให้การทีละจุด ข้อกล่าวหาไม่เหลือน้ำหนัก", { iq: 1 })), no(B("ยิ่งพูด คำตอบยิ่งไม่ตรงกับเมื่อวาน ทุกคนในห้องเห็น", { fame: -3 }))),
    P("ร้องไห้ขอความเมตตาต่อหน้าทุกคน", ab(0.3, "looks", 0.8), ok(G("น้ำตาของคุณทำให้คนกล่าวหาดูเป็นคนใจร้าย เรื่องถูกปล่อยผ่าน", {})), no(B("คนในห้องมองน้ำตาคุณอย่างเย็นชา ไม่มีใครเชื่อ", { joy: -3 }))),
    P("ชี้ตัวคนอื่นว่าเป็นคนทำ", ab(0.4, "smarts", 0.5), ok(G("หลักฐานที่คุณเตรียมไว้ทำให้คนอื่นรับกรรมแทน คุณเดินออกมาตัวเปล่า", { align: -6 })), no(B("คนที่คุณชี้มีพยานยืนยัน ตอนนี้คุณมีศัตรูเพิ่มอีกคน", { align: -4, fame: -2 }))),
    P("ขอสาบานพิสูจน์ต่อหน้าศาลบรรพชน", ab(0.3, "luck", 0.9), ok(G("ธูปดอกนั้นไม่ดับ คนเชื่อฟ้ามากกว่าเชื่อหลักฐาน", {})), no(B("ธูปดับกลางพิธีต่อหน้าทุกคน", { luck: -2 }))),
    P("แกล้งป่วยปางตายให้คดีชะงัก", ab(0.3, "health", 0.7), ok(G("คุณนอนนิ่งได้สามเดือนจนคดีถูกลืม หมอที่รู้ความจริงได้บ้านหลังใหม่", { hp: -4 })), no(B("หมออีกคนจับชีพจรคุณ แล้วหัวเราะออกมา", { hp: -2 }))),
    ...(o.ally ? [P("ให้พรรคพวกออกมายืนยันความบริสุทธิ์", ab(0.55, "smarts", 0.3), ok(G("คนที่ทุกคนเกรงใจยืนข้างคุณ คดีจบในวันเดียว", {})), no(B("พรรคพวกของคุณถอยในนาทีสุดท้าย", {})), { show: (l) => o.ally!(l) })] : []),
  ];
}
