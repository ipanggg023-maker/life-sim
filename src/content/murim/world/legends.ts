function flagged2(f: string) {
  return (l: Life) => !!l.flags[f];
}

DUEL_END.heavenlyDemon = (l, r) => {
  if (r !== "win") return "";
  l.flags.heavenlyDemon = true;
  const cult = factionById(l, "cult");
  if (cult) { cult.leader = displayName(l); cult.leaderAge = l.age; cult.unity = clamp(cult.unity + 20, 0, 100); }
  learn(l, "x_heavenly_demon", "ตำแหน่งประมุข", true);
  addFame(l, 25);
  return "คุณยืนอยู่คนสุดท้ายบนแท่นเลือด — สาวกนับหมื่นคุกเข่าพร้อมกัน: มารสวรรค์องค์ใหม่!";
};
DUEL_END.demonLord = (l, r) => {
  if (r !== "win") return "";
  l.flags.slewDemonLord = true;
  if (l.mw) (l.mw as { demonLord?: number }).demonLord = 3;
  addFame(l, 60);
  return pick(l, ["จอมมารล้มลง — ใต้หล้าเงียบไปทั้งแผ่นดิน ก่อนเสียงโห่ร้องจะดังขึ้นพร้อมกัน", "คุณยืนเหนือร่างจอมมาร ร่างกายแหลกเหลวแต่ยังหายใจ — ตำนานบทใหม่เริ่มต้นที่นี่"]);
};

