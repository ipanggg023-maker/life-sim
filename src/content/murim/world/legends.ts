/** จอมมาร: เกิดขึ้นได้นานๆ ครั้ง (บันทึกในโลก) */
function tickLegends(l: Life) {
  if (l.worldId !== "murim" || !l.alive || !l.mw) return;
  const w = l.mw as typeof l.mw & { demonLord?: number };
  if (!w.demonLord && l.age >= 12 && chance(l, w.cult >= 85 ? 0.03 : 0.004)) {
    w.demonLord = 1;
    log(l, "🌑 ฟ้าทางตะวันตกเป็นสีแดงเลือดสามวันสามคืน — ผู้เฒ่าทุกสำนักพูดคำเดียวกัน: \"จอมมารคืนชีพแล้ว\"", "bad");
  } else if (w.demonLord === 1 && chance(l, 0.2)) {
    w.demonLord = 2;
    w.unrest = clamp(w.unrest + 20, 0, 100);
    log(l, "🔥 จอมมารกวาดล้างสามหัวเมืองทางตะวันตกในเดือนเดียว — ทุกสำนักทั้งธรรมะและอธรรมต้องร่วมมือกันเป็นครั้งแรกในรอบร้อยปี", "bad");
  }
}

