// ── ผลของสกิลตามประเภทและขั้น (ขั้น 0–3 = สกิลเลเวล 1/10/25/45) ──
const PASSIVE: Record<SkillType, { cp: number[]; survival: number[]; regen: number[] }> = {
  attack: { cp: [2, 3, 4, 6], survival: [0, 0, 0, 0], regen: [0, 0, 0, 0] },
  defense: { cp: [1, 1, 2, 3], survival: [0.01, 0.02, 0.03, 0.05], regen: [0, 0, 0, 0] },
  heal: { cp: [0, 1, 1, 2], survival: [0.02, 0.03, 0.04, 0.06], regen: [1, 1, 2, 3] },
  mobility: { cp: [1, 2, 2, 3], survival: [0.01, 0.02, 0.03, 0.04], regen: [0, 0, 0, 0] },
  summon: { cp: [2, 3, 5, 7], survival: [0, 0.01, 0.01, 0.02], regen: [0, 0, 0, 0] },
  stealth: { cp: [1, 2, 3, 5], survival: [0.01, 0.02, 0.02, 0.03], regen: [0, 0, 0, 0] },
  curse: { cp: [2, 3, 5, 7], survival: [0, 0, 0, 0], regen: [0, 0, 0, 0] },
};
const ACTIVE = [0.1, 0.13, 0.17, 0.23];

export interface SkillInfo {
  name: string;
  type: SkillType;
  tier: number;
  desc: string;
  cp: number;
  survival: number;
  regen: number;
  /** โอกาสที่เพิ่มขึ้นเมื่อใช้งาน (รวมความชำนาญแล้ว) */
  boost: number;
  mastery: number;
}

/** tier มาจากตำแหน่งสกิลในสายอาชีพ — ส่งมาจาก power.ts (กัน import วน) */
export function skillInfo(life: Life, name: string, tier: number): SkillInfo {
  const [type, desc] = DEFS[name] ?? (["attack", "สกิลลึกลับที่คุณได้มาด้วยวาสนา"] as [SkillType, string]);
  const t = Math.max(0, Math.min(3, tier));
  const m = masteryOf(life, name);
  const p = PASSIVE[type];
  return {
    name,
    type,
    tier: t,
    desc,
    cp: p.cp[t] + Math.floor((m - 1) / 4),
    survival: p.survival[t],
    regen: p.regen[t],
    boost: ACTIVE[t] + (type === "attack" || type === "curse" ? 0.02 : 0) + (m - 1) * 0.01,
    mastery: m,
  };
}

/** ความชำนาญ 1–10: ได้จากการใช้สกิลในฉากจริง */
export function masteryOf(life: Life, name: string) {
  const uses = life.power?.mastery?.[name] ?? 0;
  return Math.min(10, 1 + Math.floor(uses / 2));
}

/** ข้อความผลของสกิล ที่แสดงในแท็บพลัง */
export function skillEffectText(s: SkillInfo): string {
  const parts: string[] = [];
  if (s.cp) parts.push(`พลังต่อสู้ +${s.cp}`);
  if (s.survival) parts.push(`โอกาสรอด +${Math.round(s.survival * 100)}%`);
  if (s.regen) parts.push(`สุขภาพ +${s.regen}/ปี`);
  return `ติดตัว: ${parts.join(" · ")} · ใช้งาน: ตัวเลือกพิเศษในฉากเสี่ยงตาย โอกาส +${Math.round(s.boost * 100)}% (ปีละครั้ง)`;
}
