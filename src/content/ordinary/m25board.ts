const pickFresh = (l: Life, n: number): SideQuest[] => {
  const done = new Set(String(l.flags.sqBoardDone ?? "").split(",").filter(Boolean));
  let pool = SIDE_QUESTS.filter((q) => !done.has(q.id));
  if (pool.length < n) { l.flags.sqBoardDone = ""; pool = [...SIDE_QUESTS]; }
  const out: SideQuest[] = [];
  while (out.length < n && pool.length) {
    const q = pick(l, pool);
    out.push(q);
    pool = pool.filter((x) => x !== q);
  }
  return out;
};

const sideById = (id: unknown) => SIDE_QUESTS.find((q) => q.id === id)!;
/** ระดับภารกิจตำนาน (เพิ่มทุกครั้งที่ทำสำเร็จหลังผ่าน 4/4) */
export const legendTier = (l: Life) => Number(l.flags.sysLegend ?? 0);
export const sysMastered = (l: Life) => !!l.flags.sysMastered;

/** เปิดกระดานภารกิจ: ใบแรกคือภารกิจสายอาชีพ (ถ้ายังไม่ผ่าน 4/4) อีกสองใบเป็นภารกิจระบบที่ยังไม่เคยทำ */
export function openBoard(l: Life) {
  const qs = pickFresh(l, sysMastered(l) ? 3 : 2).map((q) => q.id);
  runEvent(l, "ord.board", { a: qs[0] ?? "", b: qs[1] ?? "", c: qs[2] ?? "" });
}

const diffOf = (l: Life) => Math.min(3, Math.floor((l.sys?.level ?? 1) / 3)) + legendTier(l);
function odds(l: Life, stat: SysStat) {
  return clamp(0.5 + (effSys(l, stat) - (28 + diffOf(l) * 9)) / 35 + Number(l.flags.skillBoost ?? 0), 0.08, 0.93);
}

const takeQuest = (slot: "a" | "b" | "c"): Choice => ({
  label: (l, c) => {
    const q = sideById(c[slot]);
    return `${sysMastered(l) ? "★ " : ""}${q.name} — ${q.desc}`;
  },
  show: (_l, c) => !!c[slot],
  run: (_l, c) => {
    c.q = String(c[slot]);
    return { text: "", next: "do" };
  },
});

