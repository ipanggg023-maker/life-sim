export const countryOf = (c?: Country) => COUNTRIES[c ?? "th"];

/** แสดงเงิน (เก็บเป็นหน่วยกลาง = บาท) ในสกุลเงินของประเทศ */
export function countryMoney(c: Country | undefined, n: number) {
  const info = countryOf(c);
  const v = Math.round(Math.abs(n) * info.rate);
  return `${n < 0 ? "-" : ""}${info.symbol}${v.toLocaleString("th-TH")}`;
}

/** แปลงคำเฉพาะถิ่นไทยในข้อความ และจำนวนเงิน "… บาท" ให้เป็นของประเทศนั้น */
export function localize(text: string, c?: Country): string {
  if (!c || c === "th") return text;
  const info = COUNTRIES[c];
  let out = text;
  for (const [from, to] of info.words) if (out.includes(from)) out = out.split(from).join(to);
  out = out.replace(/([\d,]+(?:\.\d+)?)\s*(ล้าน)?บาท/g, (_m, num: string, mil?: string) => {
    const baht = parseFloat(num.replace(/,/g, "")) * (mil ? 1_000_000 : 1);
    return countryMoney(c, baht);
  });
  // ข้อความที่เขียนจำนวนเงินเป็น ฿ ไว้ตรงๆ (formatMoney)
  return out.replace(/(-?)฿([\d,]+)/g, (_m, sign: string, num: string) => countryMoney(c, (sign ? -1 : 1) * parseFloat(num.replace(/,/g, ""))));
}
