export function nameFor(r: Rng, race: NameRace, gender: Gender) {
  const p = NAMES[race] ?? NAMES.human;
  const first = pick(r, gender === "m" ? p.m : p.f);
  return { first, nick: first, last: pick(r, p.last) };
}

/** นามสกุลนี้มาจากเผ่าไหน (ใช้ตัดสินว่าจะเก็บนามสกุลตระกูลไว้ตอนเกิด) */
export const raceOfLast = (last: string) => (Object.keys(NAMES) as NameRace[]).find((r) => NAMES[r].last.includes(last));

/** ชื่อคนสำคัญของโลก: ผสมทุกเผ่า มนุษย์มากที่สุด */
export function notableName(r: Rng) {
  const race = pick(r, ["human", "human", "human", "human", "elf", "dwarf", "orc", "beastfolk", "halfling"] as NameRace[]);
  return pick(r, NAMES[race].m.concat(NAMES[race].f));
}
